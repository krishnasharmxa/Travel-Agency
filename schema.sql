-- 1. Create Packages Table
create table if not exists public.packages (
    id bigint generated by default as identity primary key,
    destination text not null,
    price integer not null,
    days integer not null,
    hotel text not null,
    image text,
    itinerary text[],
    dates text[],
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 2. Create Bookings Table
create table if not exists public.bookings (
    id text primary key,
    customer_name text not null,
    email text not null,
    id_proof text not null,
    destination text not null,
    travel_date text not null,
    status text default 'Pending',
    created_at timestamp with time zone default timezone('utc'::text, now())
);

-- 3. Enable Row Level Security (RLS)
alter table public.packages enable row level security;
alter table public.bookings enable row level security;

-- 4. Create Policies for Public Access (Allow reading and writing)
create policy "Allow public read packages" on public.packages for select using (true);
create policy "Allow public insert packages" on public.packages for insert with check (true);

create policy "Allow public read bookings" on public.bookings for select using (true);
create policy "Allow public insert bookings" on public.bookings for insert with check (true);
create policy "Allow public update bookings" on public.bookings for update using (true);

